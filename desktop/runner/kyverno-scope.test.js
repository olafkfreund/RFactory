'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const dir = path.join(__dirname, '..', '..', 'deploy', 'k8s', 'rfactory-desktops');
const NS = 'rfactory-desktops';

const policies = fs.readFileSync(path.join(dir, 'kyverno.yaml'), 'utf8')
  .split(/^---\s*$/m)
  .filter((doc) => /^kind: ClusterPolicy$/m.test(doc));

const read = (f) => fs.readFileSync(path.join(dir, f), 'utf8');

test('host/privileged policy checks Pods only, not autogenerated controller rules', () => {
  assert.match(read('kyverno.yaml'), /pod-policies\.kyverno\.io\/autogen-controllers: none/);
});

test('netpol policy refuses empty peers and namespaceSelector; infra exemption needs ArgoCD', () => {
  const k = read('kyverno.yaml');
  assert.match(k, /r\.to\.all\(p, !has\(p\.namespaceSelector\)\)/);
  assert.match(k, /has\(r\.from\) && size\(r\.from\) > 0/);
  assert.match(k, /request\.userInfo\.username == 'system:serviceaccount:argocd:argocd-application-controller'/);
  assert.doesNotMatch(k, /object\.metadata\.name in variables\.infra \|\|/);
});

test('proxy has a pinned ClusterIP Service; runner and proxy sit on the server node, away from desktops', () => {
  assert.match(read('proxy.yaml'), /kind: Service[\s\S]*clusterIP: 10\.43\.250\.11/);
  assert.match(read('proxy.yaml'), /dnsPolicy: None/);
  for (const f of ['proxy.yaml', 'runner.yaml']) {
    const y = read(f);
    assert.match(y, /nodeSelector: \{kubernetes\.io\/hostname: k3d-factory-server-0\}/, f);
    assert.match(y, /rfactory\.io\/role: desktop/, f);
  }
});

test('there are three Kyverno policies', () => assert.equal(policies.length, 3));

// No YAML parser in this repo: policies are written in a fixed block style, so scan lines.
test('every Kyverno policy rule matches only the rfactory-desktops namespace', () => {
  for (const doc of policies) {
    const name = /^ {2}name: (\S+)/m.exec(doc)[1];
    const rules = doc.match(/^ {4}- name: /gm) || [];
    const matches = doc.match(/^ {6}match:$/gm) || [];
    assert.ok(rules.length > 0, name);
    assert.equal(matches.length, rules.length, `${name}: one match per rule`);

    const lines = doc.split('\n');
    const nsLines = lines.filter((l) => /^\s*namespaces:/.test(l));
    assert.equal(nsLines.length, rules.length, `${name}: every match names namespaces`);
    for (const l of nsLines) assert.equal(l.trim(), `namespaces: [${NS}]`, name);

    assert.doesNotMatch(doc, /^\s*(namespaceSelector|exclude):/m, `${name}: no selector or exclude`);
    assert.match(doc, /^ {2}failurePolicy: Fail$/m, name);
    assert.match(doc, new RegExp(`request\\.namespace == '${NS}'`), `${name}: webhook limited to the namespace`);
  }
});
