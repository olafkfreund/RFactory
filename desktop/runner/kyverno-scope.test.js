'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const dir = path.join(__dirname, '..', '..', 'deploy', 'k8s', 'rfactory-desktops');
const NS = 'rfactory-desktops';

const policies = fs.readFileSync(path.join(dir, 'kyverno.yaml'), 'utf8')
  .split(/^---\s*$/m)
  .filter((doc) => /^kind: ClusterPolicy$/m.test(doc));

const { firstHost } = require('./preflight');
// A platform whose ranges.json value is the string "not found" has no probe hosts.
const probeCidrs = (ranges) => new Set(Object.values(ranges).filter((e) => typeof e === 'object')
  .flatMap((e) => e.probe || e.cidrs.map(firstHost).filter(Boolean)).map((h) => `${h}/32`));
const read = (f) => fs.readFileSync(path.join(dir, f), 'utf8');

test('host/privileged policy checks Pods only, not autogenerated controller rules', () => {
  assert.match(read('kyverno.yaml'), /pod-policies\.kyverno\.io\/autogen-controllers: none/);
});

test('netpol policy refuses empty peers and namespaceSelector; infra exemption needs ArgoCD', () => {
  const k = read('kyverno.yaml');
  assert.match(k, /r\.to\.all\(p, !has\(p\.namespaceSelector\)\)/);
  assert.match(k, /has\(r\.from\) && size\(r\.from\) > 0/);
  assert.match(k, /request\.userInfo\.username == 'system:serviceaccount:argocd:argocd-application-controller'/);
  assert.doesNotMatch(k, /object\.metadata\.name in variables\.infra \|\|/);
});

test('proxy has a pinned ClusterIP Service; runner and proxy sit on the server node, away from desktops', () => {
  assert.match(read('proxy.yaml'), /kind: Service[\s\S]*clusterIP: 10\.43\.250\.11/);
  assert.match(read('proxy.yaml'), /dnsPolicy: None/);
  for (const f of ['proxy.yaml', 'runner.yaml']) {
    const y = read(f);
    assert.match(y, /nodeSelector: \{kubernetes\.io\/hostname: k3d-factory-server-0\}/, f);
    assert.match(y, /rfactory\.io\/role: desktop/, f);
  }
});

test('there are three Kyverno policies', () => assert.equal(policies.length, 3));

// No YAML parser in this repo: policies are written in a fixed block style, so scan lines.
test('every Kyverno policy rule matches only the rfactory-desktops namespace', () => {
  for (const doc of policies) {
    const name = /^ {2}name: (\S+)/m.exec(doc)[1];
    const rules = doc.match(/^ {4}- name: /gm) || [];
    const matches = doc.match(/^ {6}match:$/gm) || [];
    assert.ok(rules.length > 0, name);
    assert.equal(matches.length, rules.length, `${name}: one match per rule`);

    const lines = doc.split('\n');
    const nsLines = lines.filter((l) => /^\s*namespaces:/.test(l));
    assert.equal(nsLines.length, rules.length, `${name}: every match names namespaces`);
    for (const l of nsLines) assert.equal(l.trim(), `namespaces: [${NS}]`, name);

    assert.doesNotMatch(doc, /^\s*(namespaceSelector|exclude):/m, `${name}: no selector or exclude`);
    assert.match(doc, /^ {2}failurePolicy: Fail$/m, name);
    assert.match(doc, new RegExp(`request\\.namespace == '${NS}'`), `${name}: webhook limited to the namespace`);
  }
});

test('runner has RF_ALWAYS_PROTECTED, the same host ranges Kyverno lists; every pod gets the cluster CA', () => {
  const m = /name: RF_ALWAYS_PROTECTED\s+value: '(\[.*\])'/.exec(read('runner.yaml'));
  const ranges = JSON.parse(m[1]);
  const kyv = /name: protected\s+expression: >-\s+(\[[^\]]*\])/.exec(read('kyverno.yaml'))[1].replace(/'/g, '"');
  const listed = JSON.parse(kyv.replace(/\s+/g, ' '));
  for (const r of ['192.168.0.0/16', '100.64.0.0/10', 'fd7a:115c:a1e0::/48']) assert.ok(ranges.includes(r), r);
  for (const r of ranges) assert.ok(listed.includes(r), `Kyverno also protects ${r}`);
  for (const r of ['192.168.0.0/16', '100.64.0.0/10', 'fd7a:115c:a1e0::/48']) assert.ok(listed.includes(r), r);
  for (const f of ['runner', 'proxy', 'guard', 'reaper']) {
    assert.match(read(`${f}.yaml`), /name: NODE_EXTRA_CA_CERTS, value: \/var\/run\/secrets\/kubernetes\.io\/serviceaccount\/ca\.crt/, f);
  }
});

test('TLS Secrets are mounted at /etc/rfactory/tls and the guard env names its files there', () => {
  assert.match(read('runner.yaml'), /mountPath: \/etc\/rfactory\/tls[\s\S]*secretName: rfactory-runner-tls/);
  const g = read('guard.yaml');
  assert.match(g, /mountPath: \/etc\/rfactory\/tls[\s\S]*secretName: rfactory-guard-tls/);
  for (const [k, v] of [['GUARD_TLS_KEY', 'tls.key'], ['GUARD_TLS_CERT', 'tls.crt'], ['GUARD_CLIENT_CA', 'ca.crt']]) {
    assert.match(g, new RegExp(`name: ${k}, value: /etc/rfactory/tls/${v.replace('.', '\\.')}\\}`), k);
  }
  assert.match(g, /name: GUARD_PORT, value: "9443"/);
  assert.match(g, /name: NODE_NAME\s+valueFrom: \{fieldRef: \{fieldPath: spec\.nodeName\}\}/);
});

test('proxy binds 53 as non-root through the unprivileged-port sysctl and a TCP+UDP Service', () => {
  const y = read('proxy.yaml');
  assert.match(y, /runAsNonRoot: true/);
  assert.match(y, /net\.ipv4\.ip_unprivileged_port_start, value: "0"/);
  assert.match(y, /name: dns-udp, port: 53, protocol: UDP/);
  assert.match(y, /name: dns-tcp, port: 53, protocol: TCP/);
});

test('runner media-probe egress is exactly the preflight probe hosts, TCP only, nothing protected', () => {
  const want = probeCidrs(require('../ranges/ranges.json'));
  const doc = read('networkpolicies.yaml').split(/^---\s*$/m).find((d) => /name: rfactory-runner-egress-media-probe/.test(d));
  assert.ok(doc, 'policy exists');
  assert.deepEqual(new Set([...doc.matchAll(/ipBlock: \{cidr: ([^}]+)\}/g)].map((m) => m[1])), want);
  assert.equal((doc.match(/ipBlock:/g) || []).length, want.size, 'no duplicates');
  assert.match(doc, /policyTypes: \[Egress\]/);
  assert.match(doc, /ports: \[\{protocol: TCP, port: 443\}\]/);
  assert.doesNotMatch(doc, /protocol: UDP|except|namespaceSelector/);
  const protectedNets = ['10.', '172.18.', '192.168.', '169.254.'];
  for (const c of want) assert.ok(!protectedNets.some((p) => c.startsWith(p)) && !/^100\.(6[4-9]|[7-9]\d|1[01]\d|12[0-7])\./.test(c), c);
});

test('a ranges.json platform value "not found" adds no probe host', () => {
  assert.deepEqual([...probeCidrs({ meet: 'not found', slack: { cidrs: [], probe: ['99.77.128.1'] } })], ['99.77.128.1/32']);
});

test('desktop VMIs tolerate the desktops taint; the toleration policy is cluster-wide, Fail, and scoped by matchCondition', () => {
  const life = fs.readFileSync(path.join(__dirname, 'lifecycle.js'), 'utf8');
  assert.match(life, /tolerations: \[\{ key: 'rfactory\.io\/desktops', operator: 'Equal', value: 'true' \}\]/);
  const y = read('kyverno-taint.yaml');
  assert.match(y, /^ {2}failurePolicy: Fail$/m);
  assert.match(y, /matchConditions:[\s\S]*t\.key == 'rfactory\.io\/desktops'/);
  assert.doesNotMatch(y, /^\s*namespaces:/m, 'cluster-wide rule');
  assert.match(y, /expression: "object != null && has\(object\.spec\.tolerations\)/, 'DELETE has a null object');
  assert.match(y, /operations: \[CREATE, UPDATE\]/);
  assert.match(y, /request\.namespace == 'rfactory-desktops'/);
  assert.match(y, /'kubevirt\.io'\] == 'virt-launcher'/);
  assert.match(read('guard.yaml'), /tolerations: \[\{operator: Exists\}\]/);
});

